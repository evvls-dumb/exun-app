// A verification receipt: a plain-text record of what Janus checked on this machine about one case, written so
// another person can re-check the parts that can be re-checked (file hashes, the log chain) without Janus.
//
// A receipt is not a signature. It says what this installation computed; anyone can edit a text file. What
// makes it useful is that the hashes in it can be recomputed from the original files.
import type { Assessment, GradedEvidence } from './evidence'
import { chainHead, verifyChain, type CaseLogEntry } from './casechain'
import type { Investigation } from './investigation'

const VERDICT: Record<Assessment['verdict'], string> = { supported: 'Hypothesis supported', refuted: 'Hypothesis refuted', leaning: 'Leaning, not yet conclusive', inconclusive: 'Inconclusive' }

export interface ReceiptInput {
  investigation: Investigation
  evidence: readonly GradedEvidence[]
  log: readonly CaseLogEntry[]
  assessment: Assessment
  analysed: boolean
  stale: boolean
  agent: string
  now: string
}

export function buildReceipt(i: ReceiptInput): string {
  const inv = i.investigation
  const chain = verifyChain(i.log)
  const L: string[] = []
  L.push('JANUS VERIFICATION RECEIPT', '==========================', '')
  L.push(`Case:        ${inv.title}`, `Case id:     ${inv.id}`, `Generated:   ${i.now}`, `Generated by: ${i.agent}`)
  if (inv.incident) L.push(`Incident:    ${inv.incident.from} to ${inv.incident.to}`)
  L.push('')
  L.push('Analysis')
  if (!i.analysed) L.push('  Not run. No verdict was produced for this case.')
  else {
    const a = i.assessment
    L.push(`  Run:       ${inv.analysis?.at} by ${inv.analysis?.by}`, `  Digest:    ${inv.analysis?.digest}`, `  State:     ${i.stale ? 'STALE, the case has changed since this was run' : 'current'}`)
    L.push(`  Verdict:   ${VERDICT[a.verdict]}`)
    L.push(`  Estimate:  ${a.estimate === null ? 'none (no evidence takes a side)' : `${Math.round(a.estimate * 100)}%`} at ${a.confidenceLabel.toLowerCase()} confidence`)
    L.push(`  Open discrepancies: ${a.discrepancies.length}`)
  }
  L.push('')
  L.push(`Evidence (${i.evidence.length})`)
  if (i.evidence.length === 0) L.push('  None filed.')
  for (const e of i.evidence) {
    const v = e.verification
    L.push(`  - ${e.title}`)
    L.push(`      id ${e.id} · ${e.type} · filed by ${e.agentId} · ${e.addedAt}`)
    L.push(`      grade ${e.grade} (${e.score}/100) · stance ${e.stance}`)
    L.push(`      seal: ${v ? `${v.state}${v.notes.length ? ` (${v.notes.join('; ')})` : ''}` : 'none recorded'}`)
    if (e.fileName) L.push(`      file: ${e.fileName}${e.fileBytes !== undefined ? ` (${e.fileBytes} bytes)` : ''}`)
    L.push(`      sha256: ${e.fileSha256 ?? 'not a file, nothing to hash'}`)
    if (e.chainHead) L.push(`      field-unit chain head: ${e.chainHead}`)
  }
  L.push('')
  L.push('Case log')
  L.push(`  Entries:    ${i.log.length}`, `  Chain:      ${chain.ok ? 'intact' : `BROKEN at entry ${chain.at}`}`, `  Head:       ${chainHead(i.log) ?? 'empty'}`)
  L.push('')
  L.push('How to re-check', '  1. Take the original file named above and run: sha256sum <file>   (Windows: certutil -hashfile <file> SHA256)', '  2. The result must equal the sha256 line. If it does not, the file is not the one Janus recorded.', '  3. For the case log, each entry hashes sha256(prev|seq|time|actor|action|detail); the first entry\'s prev is "genesis".', '', 'This receipt records what Janus computed on the machine named above. It is not signed.')
  return L.join('\n') + '\n'
}
